import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const generatedDir = fileURLToPath(new URL('../frontend/src/api/generated/', import.meta.url));
const headerPattern = new RegExp('^' + '/' + '/' + ' This file is auto-generated by @hey-api/openapi-ts\\r?\\n\\r?\\n?');
const blockPattern = new RegExp('/' + '\\*\\*' + '[\\s\\S]*?' + '\\*' + '/', 'g');
const linePattern = new RegExp('(^|\\s)' + '/' + '/' + '.*$', 'gm');
const trailingSpacePattern = new RegExp('[ \\t]+$', 'gm');

for (const filePath of generatedFiles(generatedDir)) {
  const source = readFileSync(filePath, 'utf8')
    .replace(headerPattern, '')
    .replace(blockPattern, '')
    .replace(linePattern, '$1')
    .replace(trailingSpacePattern, '');

  writeFileSync(filePath, source);
}

function generatedFiles(dir) {
  const files = [];

  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const entryPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...generatedFiles(entryPath));
    } else if (entry.name.endsWith('.ts')) {
      files.push(entryPath);
    }
  }

  return files;
}
